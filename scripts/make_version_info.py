"""Create Windows executable metadata from the central product branding."""
from pathlib import Path
import json
import re


def make_version_info(branding_path: Path, destination: Path) -> None:
    branding = json.loads(branding_path.read_text(encoding='utf-8'))
    version = branding['version']
    executable_name = branding['executable_name']
    if not re.fullmatch(r'[A-Za-z][A-Za-z0-9_-]{0,63}', executable_name):
        raise ValueError('Executable name must use letters, numbers, hyphens or underscores.')
    if not re.fullmatch(r'\d+\.\d+\.\d+(?:\.\d+)?', version):
        raise ValueError('Release version must contain three or four numeric components.')
    numbers = [int(part) for part in version.split('.')]
    numbers += [0] * (4 - len(numbers))
    if any(part > 65535 for part in numbers):
        raise ValueError('Windows version components must not exceed 65535.')
    for key in ('display_name', 'publisher'):
        if not isinstance(branding[key], str) or not branding[key].strip() or any(ord(c) < 32 for c in branding[key]):
            raise ValueError('Product name and publisher must be nonempty single-line strings.')
    values = {
        'CompanyName': branding['publisher'], 'FileDescription': branding['display_name'],
        'FileVersion': version, 'InternalName': executable_name,
        'LegalCopyright': 'Copyright (c) 2026 ' + branding['publisher'],
        'OriginalFilename': executable_name + '.exe', 'ProductName': branding['display_name'],
        'ProductVersion': version,
    }
    strings = ',\n'.join(f'    StringStruct({key!r}, {value!r})' for key, value in values.items())
    destination.write_text(
        '# Generated by scripts/make_version_info.py from branding.json.\n'
        'VSVersionInfo(\n'
        f'  ffi=FixedFileInfo(filevers={tuple(numbers)!r}, prodvers={tuple(numbers)!r},\n'
        '    mask=0x3f, flags=0x0, OS=0x40004, fileType=0x1, subtype=0x0, date=(0, 0)),\n'
        "  kids=[StringFileInfo([StringTable('040904B0', [\n" + strings +
        "\n  ])]), VarFileInfo([VarStruct('Translation', [1033, 1200])])]\n)\n", encoding='utf-8')


if __name__ == '__main__':
    root = Path(__file__).resolve().parents[1]
    make_version_info(root / 'branding.json', root / 'packaging' / 'windows-version.txt')
